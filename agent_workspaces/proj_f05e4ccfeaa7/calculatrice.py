"""Module calculatrice simple avec opérations de base."""

def add(a, b):
    """Additionne deux nombres.
    
    Args:
        a: Premier nombre
        b: Deuxième nombre
        
    Returns:
        La somme de a et b
    """
    return a + b

def multiply(a, b):
    """Multiplie deux nombres.
    
    Args:
        a: Premier nombre
        b: Deuxième nombre
        
    Returns:
        Le produit de a et b
    """
    return a * b